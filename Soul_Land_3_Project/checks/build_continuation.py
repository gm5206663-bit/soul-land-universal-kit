"""BUILD_CONTINUATION — regenerate CONTINUATION_PROMPT.md from the derived state.

The hand-written version said "end of Chapter 28" while the story was at chapter 61. Generated files
do not rot. Run after every chapter; `verify_stale.py` enforces it.

Usage:
    python3 checks/build_continuation.py
    python3 checks/build_continuation.py --check
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import state as STATE
import ensemble_schedule as ES

