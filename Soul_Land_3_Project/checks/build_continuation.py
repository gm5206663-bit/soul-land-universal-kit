    A("6. **`PROBLEM_INVENTORY.md`** — what is owed. 🔴 **Read the CURRENT open list, not a name\n   remembered from a previous session.** On 2026-08-29 this generator hard-coded \"F1 is the\n   blocker\" and \"OWED BEFORE ANY COMBAT CHAPTER — F1\" for 22 chapters after F1 had closed\n   in ch40 — and four documents inherited the false claim from it.")
    A("")
    A("## Current state")
    A("")
    # verify.py's SYNC check looks for the literal "rank <N>" and the bare spiritual-power number.
    A(f"- **rank {st['current_rank']} — {st['current_realm']}** · ceiling {st['rank_ceiling']} ({st['rank_ceiling_reason']})")
    A(f"- **Effective combat power: 🔴 {st['effective_realm']} ({st['effective_rank_band'][0]}–{st['effective_rank_band'][1]})**, ceiling {st['effective_realm']} peak")
    A(f"- **{st['rings']['count']} {st['rings']['colour']} rings**, perfectly compatible · spiritual power **{st['current_spiritual_power']}** · hawk **{st['current_hawk_years']:,}**")
